package com.cosmos.simulation.io.input.model;

public class VecTemp {
  public String x;
  public String y;
  public String z;

  public VecTemp() {
    this.x = "0";
    this.y = "0";
    this.z = "0";
  }

  public VecTemp(String x, String y, String z) {
    this.x = x;
    this.y = y;
    this.z = z;
  }
}
